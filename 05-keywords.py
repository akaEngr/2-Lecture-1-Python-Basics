
# ! Keywords in python

# ! Keywords are the reserved words in python and can not be use as identifier

"""
| **Keyword** | **Use / Meaning**                                                 |
| ----------- | ----------------------------------------------------------------- |
| `False`     | Boolean value for false condition                                 |
| `True`      | Boolean value for true condition                                  |
| `None`      | Represents the absence of a value (null)                          |
| `and`       | Logical AND operator                                              |
| `or`        | Logical OR operator                                               |
| `not`       | Logical NOT operator                                              |
| `as`        | Used to create alias (e.g., `import math as m`)                   |
| `assert`    | Used for debugging; checks a condition                            |
| `async`     | Declares asynchronous functions (async/await)                     |
| `await`     | Used to wait for an asynchronous function                         |
| `break`     | Exits the nearest loop immediately                                |
| `class`     | Defines a class                                                   |
| `continue`  | Skips current loop iteration and moves to next                    |
| `def`       | Defines a function                                                |
| `del`       | Deletes variables, objects, or items in lists/dicts               |
| `elif`      | Else-if condition in `if` statements                              |
| `else`      | Defines block of code if condition is false                       |
| `except`    | Handles exceptions in try-except block                            |
| `finally`   | Defines cleanup code that always runs in try-except               |
| `for`       | Looping construct (iterate over sequence)                         |
| `from`      | Used with import to import specific parts (`from math import pi`) |
| `global`    | Declares global variables inside a function                       |
| `if`        | Conditional statement                                             |
| `import`    | Imports modules or libraries                                      |
| `in`        | Membership operator (`if x in list`)                              |
| `is`        | Identity operator (checks if two objects are same in memory)      |
| `lambda`    | Creates anonymous (inline) functions                              |
| `nonlocal`  | Refers to variables in the nearest enclosing (non-global) scope   |
| `pass`      | Placeholder; does nothing (used as empty block)                   |
| `raise`     | Raises an exception                                               |
| `return`    | Exits a function and optionally returns a value                   |
| `try`       | Defines block of code to test for errors                          |
| `while`     | Loop construct that runs while condition is true                  |
| `with`      | Context manager (used with resources like files)                  |
| `yield`     | Used in generators to return values lazily                        |

"""